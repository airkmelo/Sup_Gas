-- ---------- Pessoas, contatos, clientes, funcionarios ----------------
CREATE TABLE pessoa (
    pessoa_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(120) NOT NULL,
    cpf       VARCHAR(14)  UNIQUE,
    endereco  VARCHAR(200) NOT NULL
);

CREATE TABLE tipo_contato (
    tipo_contato_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao       VARCHAR(40) NOT NULL UNIQUE      -- telefone, email
);

CREATE TABLE contato_pessoa (
    contato_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pessoa_id       INT NOT NULL REFERENCES pessoa(pessoa_id) ON DELETE CASCADE,
    tipo_contato_id INT NOT NULL REFERENCES tipo_contato(tipo_contato_id),
    descricao       VARCHAR(120) NOT NULL,           -- 9 9123 4567 / joao@gmail.com
    UNIQUE (pessoa_id, tipo_contato_id, descricao)
);

CREATE TABLE cliente (
    cliente_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pessoa_id  INT NOT NULL UNIQUE REFERENCES pessoa(pessoa_id)
);

CREATE TABLE funcionario (
    funcionario_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pessoa_id      INT NOT NULL UNIQUE REFERENCES pessoa(pessoa_id),
    comissao       DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (comissao >= 0)
);

-- ---------- Servicos (mecanica e petshop) ----------------------------
CREATE TABLE tipo_servico (
    tipo_servico_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao       VARCHAR(40) NOT NULL UNIQUE      -- mecanico, pet shop
);

CREATE TABLE servico (
    servico_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_servico    VARCHAR(100) NOT NULL,
    descricao       TEXT NOT NULL,
    preco           DECIMAL(10,2) NOT NULL CHECK (preco >= 0),
    tipo_servico_id INT NOT NULL REFERENCES tipo_servico(tipo_servico_id)
);

-- ---------- Carros e lavacao -----------------------------------------
CREATE TABLE carro (
    carro_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INT NOT NULL REFERENCES cliente(cliente_id),
    placa      VARCHAR(10)  NOT NULL UNIQUE,
    modelo     VARCHAR(100) NOT NULL,
    cor        VARCHAR(40)  NOT NULL
);

CREATE TABLE lavacao (
    id_lavacao         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carro_id           INT NOT NULL REFERENCES carro(carro_id),
    hora_chegada       TIMESTAMP NOT NULL DEFAULT now(),
    data_hora_entrega  TIMESTAMP NOT NULL,           -- hora prevista de entrega
    preco              DECIMAL(10,2) CHECK (preco >= 0),
    status             VARCHAR(20) NOT NULL DEFAULT 'EM_ANDAMENTO'
                       CHECK (status IN ('EM_ANDAMENTO','CONCLUIDA','CANCELADA'))
);

-- ---------- Pet shop -------------------------------------------------
CREATE TABLE animal (
    animal_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INT NOT NULL REFERENCES cliente(cliente_id),   -- dono
    nome       VARCHAR(100) NOT NULL,
    especie    VARCHAR(50)  NOT NULL,
    raca       VARCHAR(80)  NOT NULL,
    sexo       VARCHAR(15)  NOT NULL
);

CREATE TABLE atendimento_pet (
    id_atendimento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id     INT NOT NULL REFERENCES cliente(cliente_id), -- quem levou (pode nao ser o dono)
    animal_id      INT NOT NULL REFERENCES animal(animal_id),
    hora_chegada   TIMESTAMP NOT NULL,
    hora_retirada  TIMESTAMP,
    -- regra: tudo no mesmo dia
    CHECK (hora_retirada IS NULL
           OR (hora_retirada >= hora_chegada
               AND hora_retirada::date = hora_chegada::date))
);

CREATE TABLE servico_atendimento_pet (
    id_servico_atendimento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_atendimento INT NOT NULL REFERENCES atendimento_pet(id_atendimento) ON DELETE CASCADE,
    servico_id     INT NOT NULL REFERENCES servico(servico_id),
    funcionario_id INT NOT NULL REFERENCES funcionario(funcionario_id),
    preco_cobrado  DECIMAL(10,2) NOT NULL CHECK (preco_cobrado >= 0)
);

-- ---------- Conveniencia / estoque -----------------------------------
CREATE TABLE produto (
    id_produto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(100) NOT NULL,
    preco      DECIMAL(10,2) NOT NULL CHECK (preco >= 0),
    qtd_atual  INT NOT NULL DEFAULT 0 CHECK (qtd_atual >= 0)   -- nunca fica negativo
);

CREATE TABLE local_venda (
    local_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(60) NOT NULL UNIQUE            -- Loja de Conveniencia, Drive Thru
);

CREATE TABLE venda (
    id_venda   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INT REFERENCES cliente(cliente_id),   -- opcional
    carro_id   INT REFERENCES carro(carro_id),       -- opcional
    data       DATE NOT NULL DEFAULT CURRENT_DATE,
    hora       TIME NOT NULL DEFAULT CURRENT_TIME,
    local_id   INT NOT NULL REFERENCES local_venda(local_id)
);

CREATE TABLE item_venda (
    id_venda       INT NOT NULL REFERENCES venda(id_venda) ON DELETE CASCADE,
    id_produto     INT NOT NULL REFERENCES produto(id_produto),
    quantidade     INT NOT NULL CHECK (quantidade > 0),
    preco_unitario DECIMAL(10,2) NOT NULL CHECK (preco_unitario >= 0),
    PRIMARY KEY (id_venda, id_produto)
);

CREATE TABLE abastecimento (
    id_entrega   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id   INT NOT NULL REFERENCES produto(id_produto),
    qtd_produto  INT NOT NULL CHECK (qtd_produto > 0),
    data_entrega DATE NOT NULL
);

-- ---------- Mecanica -------------------------------------------------
CREATE TABLE os_mecanica (
    id_osm       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carro_id     INT NOT NULL REFERENCES carro(carro_id),
    cliente_id   INT NOT NULL REFERENCES cliente(cliente_id),
    hora_entrada TIMESTAMP NOT NULL,
    hora_saida   TIMESTAMP,
    CHECK (hora_saida IS NULL OR hora_saida >= hora_entrada)
);

CREATE TABLE produto_adquirido (
    id_produto_adquirido INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_osm         INT NOT NULL REFERENCES os_mecanica(id_osm) ON DELETE CASCADE,
    produto_id     INT NOT NULL REFERENCES produto(id_produto),
    funcionario_id INT NOT NULL REFERENCES funcionario(funcionario_id),
    quantidade     INT NOT NULL CHECK (quantidade > 0),
    preco          DECIMAL(10,2) NOT NULL CHECK (preco >= 0)
);

CREATE TABLE servico_realizado (
    id_servico_realizado INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_osm         INT NOT NULL REFERENCES os_mecanica(id_osm) ON DELETE CASCADE,
    funcionario_id INT NOT NULL REFERENCES funcionario(funcionario_id),
    servico_id     INT NOT NULL REFERENCES servico(servico_id),
    preco          DECIMAL(10,2) NOT NULL CHECK (preco >= 0),
    hora_inicio    TIMESTAMP NOT NULL,
    hora_fim       TIMESTAMP,
    CHECK (hora_fim IS NULL OR hora_fim >= hora_inicio)
);

