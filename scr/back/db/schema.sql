-- ---------- Seguranca no Supabase ------------------------------------
-- O Supabase expoe o schema "public" por uma API publica (PostgREST).
-- Ligando o RLS sem criar policies, essa API nao enxerga nada.
-- Seu back-end Java conecta direto como "postgres" e nao e afetado.
DO $$
DECLARE t record;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t.tablename);
  END LOOP;
END $$;